import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

// =============================================================================
// Configuration
// =============================================================================

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TYPES_DIR = path.join(PACKAGE_ROOT, 'src', 'types');
const TYPES_GENERATED_DIR = path.join(TYPES_DIR, 'generated');
const API_GENERATED_DIR = path.join(PACKAGE_ROOT, 'src', 'api', 'generated');

const DEFAULT_URL = 'http://localhost:8080/v3/api-docs';
const API_PREFIX = '/api/v1';
const COMMON_DOMAIN = 'common';

const DOMAIN_OVERRIDES: Record<string, string> = {
	UserDTO: 'users',
	UserLookupDTO: 'users',
	GearCategory: 'gear',
	DiveSiteType: 'dive-sites',
}

const WRAPPED_API_DOMAINS = new Set(['auth']);
const MARKER = '// AUTO-GENERATED by scripts/generate-api.ts';
const HEADER = `${MARKER}: do not edit by hand.\n// Regenerate with: pnpm --filter @frontend/shared generate:api\n`;

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'patch'] as const;
type HttpMethod = (typeof HTTP_METHODS)[number];
const METHODS_WITH_BODY = new Set<HttpMethod>(['post', 'put', 'patch']);

const SCHEMA_REF_PREFIX = '#/components/schemas/';
const VALID_IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

interface SchemaObject {
	$ref?: string;
	type?: string | string[];
	format?: string;
	enum?: unknown[];
	nullable?: boolean;
	properties?: Record<string, SchemaObject>;
	required?: string[];
	items?: SchemaObject;
	additionalProperties?: boolean | SchemaObject;
	allOf?: SchemaObject[];
	oneOf?: SchemaObject[];
	anyOf?: SchemaObject[];
}

interface MediaTypes {
	content?: Record<string, { schema?: SchemaObject }>;
}

interface ParameterObject {
	name: string;
	in: 'path' | 'query' | 'header' | 'cookie';
	required?: boolean;
	schema?: SchemaObject;
}

interface Operation {
	operationId?: string;
	summary?: string;
	tags?: string[];
	parameters?: ParameterObject[];
	requestBody?: MediaTypes & { required?: boolean };
	responses?: Record<string, MediaTypes>;
}

interface Spec {
	paths?: Record<string, Partial<Record<HttpMethod, Operation>>>;
	components?: { schemas?: Record<string, SchemaObject> };
}

interface OperationEntry {
	path: string;
	method: HttpMethod;
	operation: Operation;
	domain: string;
}

// =============================================================================
// Input
// =============================================================================

const readArgument = (name: string): string | undefined => {
	const index = process.argv.indexOf(`--${name}`);
	return index >= 0 ? process.argv[index + 1] : undefined;
}

const loadSpec = async (): Promise<Spec> => {
	const inputFile = readArgument('input');

	if(inputFile) {
		const filePath = path.resolve(process.cwd(), inputFile);
		
        console.log(`Reading OpenAPI spec from ${filePath}`);
		return JSON.parse(await readFile(filePath, 'utf8')) as Spec;
	}

	const url = readArgument('url') ?? process.env.OPENAPI_URL ?? DEFAULT_URL;
	console.log(`Downloading OpenAPI spec from ${url}`);

	let response: Response;
	try {
		response = await fetch(url);
	} catch(error) {
		throw new Error(`Unable to reach ${url}: is the backend running? (${(error as Error).message})`);
	}

	if(!response.ok) {
		throw new Error(`Unable to download the spec from ${url}: HTTP ${response.status}`);
	}

	return (await response.json()) as Spec;
}

// =============================================================================
// Operations and domains
// =============================================================================

const slugify = (tag: string): string => tag.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || COMMON_DOMAIN;

const listOperations = (spec: Spec): OperationEntry[] => {
	const entries: OperationEntry[] = [];

	for(const [operationPath, pathItem] of Object.entries(spec.paths ?? {})) {
		for(const method of HTTP_METHODS) {
			const operation = pathItem[method];
			
            if(!operation) continue;

			entries.push({
				path: operationPath,
				method,
				operation,
				domain: slugify(operation.tags?.[0] ?? COMMON_DOMAIN),
			});
		}
	}

	return entries.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

const collectRefs = (schema: SchemaObject | undefined, refs: Set<string>): void => {
	if(!schema) return;

	if(schema.$ref?.startsWith(SCHEMA_REF_PREFIX)) {
		refs.add(schema.$ref.slice(SCHEMA_REF_PREFIX.length));
	}

	Object.values(schema.properties ?? {}).forEach((property) => collectRefs(property, refs));
	collectRefs(schema.items, refs);
	
    if(typeof schema.additionalProperties === 'object') collectRefs(schema.additionalProperties, refs);
	
    [...(schema.allOf ?? []), ...(schema.oneOf ?? []), ...(schema.anyOf ?? [])].forEach((part) => collectRefs(part, refs));
}

const expandRefs = (start: Set<string>, schemas: Record<string, SchemaObject>): Set<string> => {
	const result = new Set<string>();
	const queue = [...start];

	while(queue.length > 0) {
		const name = queue.pop()!;
		
        if(result.has(name)) continue;
		
        result.add(name);

		const nested = new Set<string>();
		collectRefs(schemas[name], nested);
		nested.forEach((child) => {
			if(!result.has(child)) queue.push(child);
		});
	}

	return result;
}

const mapSchemasToDomains = (operations: OperationEntry[], schemas: Record<string, SchemaObject>): Map<string, Set<string>> => {
	const usage = new Map<string, Set<string>>();

	for(const { operation, domain } of operations) {
		const directRefs = new Set<string>();
		operation.parameters?.forEach((parameter) => collectRefs(parameter.schema, directRefs));
		
        Object.values(operation.requestBody?.content ?? {}).forEach((media) => collectRefs(media.schema, directRefs));
		Object.values(operation.responses ?? {}).forEach((response) =>
			Object.values(response.content ?? {}).forEach((media) => collectRefs(media.schema, directRefs)),
		);

		for(const name of expandRefs(directRefs, schemas)) {
			const set = usage.get(name) ?? new Set<string>();
			
            set.add(domain);
			usage.set(name, set);
		}
	}

	return usage;
}

const resolveSchemaDomain = (schemaName: string, usage: Map<string, Set<string>>): string => {
	const override = DOMAIN_OVERRIDES[schemaName];
	if(override) return override;

	const domains = usage.get(schemaName);
	return domains?.size === 1 ? [...domains][0] : COMMON_DOMAIN;
}

const valuesConstName = (schemaName: string): string => `${schemaName.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()}_VALUES`;

const isStringEnum = (schema: SchemaObject): schema is SchemaObject & { enum: string[] } =>
	Array.isArray(schema.enum) && schema.enum.length > 0 && schema.enum.every((value) => typeof value === 'string');

const renderTypesFile = (schemaNames: string[], schemas: Record<string, SchemaObject>): string => {
	const lines: string[] = [
		HEADER,
		"import type { components } from './generated/openapi';",
		'',
		"type Schemas = components['schemas'];",
		'',
	];

	for(const name of schemaNames) {
		const schema = schemas[name];
		lines.push(`export type ${name} = Schemas['${name}'];`);

		if(isStringEnum(schema)) {
			const values = schema.enum.map((value) => `'${value}'`).join(', ');
            lines.push(`export const ${valuesConstName(name)} = [${values}] as const satisfies readonly ${name}[];`, '');
		}
	}

	return `${lines.join('\n').trimEnd()}\n`;
}

const schemaToTs = (schema: SchemaObject | undefined, typeImports: Set<string>): string => {
	if(!schema) return 'unknown';

	if(schema.$ref?.startsWith(SCHEMA_REF_PREFIX)) {
		const name = schema.$ref.slice(SCHEMA_REF_PREFIX.length);
		
        if(!VALID_IDENTIFIER.test(name)) return 'unknown';

		typeImports.add(name);
		return name;
	}

	const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
	const nullable = schema.nullable === true || types.includes('null');
	const mainType = types.find((type) => type !== 'null');

	let result: string;

	if(isStringEnum(schema)) {
		result = schema.enum.map((value) => `'${value}'`).join(' | ');
	} else {
		switch(mainType) {
			case 'string':
				result = schema.format === 'binary' ? 'Blob' : 'string';
				break;
			case 'integer':
			case 'number':
				result = 'number';
				break;
			case 'boolean':
				result = 'boolean';
				break;
			case 'array': {
				const item = schemaToTs(schema.items, typeImports);
				result = /[|&]/.test(item) ? `(${item})[]` : `${item}[]`;
				break;
			}
			case 'object':
				result = typeof schema.additionalProperties === 'object'
					? `Record<string, ${schemaToTs(schema.additionalProperties, typeImports)}>`
					: 'Record<string, unknown>';
				break;
			default:
				result = 'unknown';
		}
	}

	return nullable ? `${result} | null` : result;
}

const isJsonMedia = (mediaType: string): boolean => mediaType.includes('json') || mediaType === '*/*';

const resolveResponse = (operation: Operation, typeImports: Set<string>): { type: string; isBlob: boolean } => {
	const successCode = Object.keys(operation.responses ?? {}).sort((a, b) => a.localeCompare(b)).find((code) => code.startsWith('2'));
	const content = successCode ? operation.responses?.[successCode]?.content : undefined;

	if(!content) return { type: 'void', isBlob: false };

	const entries = Object.entries(content).filter(([, media]) => media.schema !== undefined);
	const json = entries.find(([mediaType]) => isJsonMedia(mediaType));

	if(json) {
		const type = schemaToTs(json[1].schema, typeImports);
		return type === 'Blob' ? { type: 'Blob', isBlob: true } : { type, isBlob: false };
	}

	return entries.length > 0 ? { type: 'Blob', isBlob: true } : { type: 'void', isBlob: false };
}

const functionName = (entry: OperationEntry): string => {
	const raw = entry.operation.operationId ?? `${entry.method}_${entry.path}`;
	const cleaned = raw.replace(/[^\w$]/g, '_');

	return VALID_IDENTIFIER.test(cleaned) ? cleaned : `_${cleaned}`;
}

const renderUrl = (operationPath: string): string => {
	if(!operationPath.startsWith(API_PREFIX)) {
		console.warn(`Path "${operationPath}" does not start with ${API_PREFIX}: used as is`);
	}

	const relative = operationPath.startsWith(API_PREFIX) ? operationPath.slice(API_PREFIX.length) : operationPath;

	if(!relative.includes('{')) return `'${relative}'`;

	return `\`${relative.replace(/\{([^}]+)\}/g, (_, name: string) => `\${encodeURIComponent(String(${name}))}`)}\``;
}

const pathParameters = (entry: OperationEntry): ParameterObject[] => {
	const declared = (entry.operation.parameters ?? []).filter((parameter) => parameter.in === 'path');
	const order = [...entry.path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);

	return order.map((name) => declared.find((parameter) => parameter.name === name) ?? { name, in: 'path', required: true });
}

const renderOperation = (entry: OperationEntry, typeImports: Set<string>, helperImports: Set<string>): string => {
	const { operation, method } = entry;
	const name = functionName(entry);
	const signature: string[] = [];
	const configParts: string[] = [];

	for(const parameter of pathParameters(entry)) {
		signature.push(`${parameter.name}: ${schemaToTs(parameter.schema ?? { type: 'string' }, typeImports)}`);
	}

	let bodyExpression: string | null = null;
	const bodyContent = operation.requestBody?.content ?? {};
	const multipart = bodyContent['multipart/form-data']?.schema;
	const jsonBody = Object.entries(bodyContent).find(([mediaType]) => isJsonMedia(mediaType))?.[1].schema;

	if(multipart?.properties) {
		const requiredFields = new Set(multipart.required ?? []);
		const fieldNames: string[] = [];

		for(const [fieldName, fieldSchema] of Object.entries(multipart.properties)) {
			const isFile = fieldSchema.format === 'binary';
			const type = isFile ? 'UploadFile' : schemaToTs(fieldSchema, typeImports);
			
            signature.push(`${fieldName}${requiredFields.has(fieldName) ? '' : '?'}: ${type}`);
			fieldNames.push(fieldName);
		}

		helperImports.add('UploadFile');
		helperImports.add('toFormData');
		bodyExpression = `toFormData({ ${fieldNames.join(', ')} })`;
	} else if(jsonBody) {
		const optional = operation.requestBody?.required === false ? '?' : '';
		signature.push(`body${optional}: ${schemaToTs(jsonBody, typeImports)}`);
		
        bodyExpression = 'body';
	}

	const queryParameters = (operation.parameters ?? []).filter((parameter) => parameter.in === 'query');

	if(queryParameters.length > 0) {
		const fields = queryParameters
			.map((parameter) => `${parameter.name}${parameter.required ? '' : '?'}: ${schemaToTs(parameter.schema, typeImports)}`)
			.join('; ');
		const optional = queryParameters.some((parameter) => parameter.required) ? '' : '?';

		signature.push(`query${optional}: { ${fields} }`);
		configParts.push('params: query');
	}

	const response = resolveResponse(operation, typeImports);
	if(response.isBlob) configParts.push("responseType: 'blob'");

	const url = renderUrl(entry.path);
	const config = configParts.length > 0 ? `{ ${configParts.join(', ')} }` : null;

	let call: string;
	if(METHODS_WITH_BODY.has(method)) {
		const args = [url, bodyExpression ?? 'undefined', config].filter((arg): arg is string => arg !== null);
		call = `getApiClient().http.${method}<${response.type}>(${args.join(', ')})`;
	} else {
		const args = [url, config].filter((arg): arg is string => arg !== null);
		call = `getApiClient().http.${method}<${response.type}>(${args.join(', ')})`;
	}

	const resultExpression = response.type === 'void' ? '.then(() => undefined)' : '.then((response) => response.data)';
	const comment = operation.summary ? `/** ${operation.summary.replaceAll('*/', '*\\/')} */\n` : '';

	return `${comment}export const ${name} = (${signature.join(', ')}): Promise<${response.type}> =>\n\t${call}${resultExpression};\n`;
}

const renderApiFile = (entries: OperationEntry[]): string => {
	const typeImports = new Set<string>();
	const helperImports = new Set<string>();

	const functions = entries.map((entry) => renderOperation(entry, typeImports, helperImports));

	const imports: string[] = [];
	if(typeImports.size > 0) {
		imports.push(`import type { ${[...typeImports].sort((a, b) => a.localeCompare(b)).join(', ')} } from '../../types';`);
	}
	
    imports.push("import { getApiClient } from '../api-client';");
	if(helperImports.has('toFormData')) {
		imports.push("import { toFormData, type UploadFile } from '../upload';");
	}

	return `${HEADER}\n${imports.join('\n')}\n\n${functions.join('\n')}`;
}

const cleanGeneratedFiles = async (directory: string): Promise<void> => {
	let entries: string[] = [];
	try {
		entries = await readdir(directory);
	} catch {
		return;
	}

	for(const entry of entries.filter((file) => file.endsWith('.ts'))) {
		const filePath = path.join(directory, entry);
		const content = await readFile(filePath, 'utf8');
		
        if(content.startsWith(MARKER)) {
			await rm(filePath);
		}
	}
}

const main = async (): Promise<void> => {
	const spec = await loadSpec();
	const schemas = spec.components?.schemas ?? {};
	const operations = listOperations(spec);

	const ast = await openapiTS(spec as unknown as OpenAPI3, { alphabetize: true });
	const openapiTypes = `${HEADER}\n${astToString(ast)}`;

	const usage = mapSchemasToDomains(operations, schemas);
	const schemasByDomain = new Map<string, string[]>();

	for(const name of Object.keys(schemas).sort((a, b) => a.localeCompare(b))) {
		if(!VALID_IDENTIFIER.test(name)) {
			console.warn(`Skipping schema "${name}": not a valid TypeScript identifier (still available via components['schemas'])`);
			continue;
		}

		const domain = resolveSchemaDomain(name, usage);
		schemasByDomain.set(domain, [...(schemasByDomain.get(domain) ?? []), name]);
	}

	const operationsByDomain = new Map<string, OperationEntry[]>();
	for(const entry of operations) {
		operationsByDomain.set(entry.domain, [...(operationsByDomain.get(entry.domain) ?? []), entry]);
	}

	const typeDomains = [...schemasByDomain.keys()].sort((a, b) => a.localeCompare(b));
	const apiDomains = [...operationsByDomain.keys()].sort((a, b) => a.localeCompare(b));

	await rm(TYPES_GENERATED_DIR, { recursive: true, force: true });
	await cleanGeneratedFiles(TYPES_DIR);
	await mkdir(TYPES_GENERATED_DIR, { recursive: true });

	await writeFile(path.join(TYPES_GENERATED_DIR, 'openapi.ts'), openapiTypes);
	for(const domain of typeDomains) {
		await writeFile(path.join(TYPES_DIR, `${domain}.ts`), renderTypesFile(schemasByDomain.get(domain)!, schemas));
	}
	await writeFile(
		path.join(TYPES_DIR, 'index.ts'),
		[
			HEADER,
			"export type { components, paths } from './generated/openapi';",
			...typeDomains.map((domain) => `export * from './${domain}';`),
			'',
		].join('\n'),
	);

	await rm(API_GENERATED_DIR, { recursive: true, force: true });
	await mkdir(API_GENERATED_DIR, { recursive: true });

	for(const domain of apiDomains) {
		await writeFile(path.join(API_GENERATED_DIR, `${domain}.ts`), renderApiFile(operationsByDomain.get(domain)!));
	}
	await writeFile(
		path.join(API_GENERATED_DIR, 'index.ts'),
		[
			HEADER,
			...apiDomains
				.map((domain) =>
					WRAPPED_API_DOMAINS.has(domain)
						? `// ${domain}: wrapped by src/api/${domain}.ts`
						: `export * from './${domain}';`,
				),
			'',
		].join('\n'),
	);

	console.log(`\nTypes: ${Object.keys(schemas).length} schemas in src/types/`);
	for(const domain of typeDomains) {
		console.log(`  ${`${domain}.ts`.padEnd(22)} ${schemasByDomain.get(domain)!.length} types`);
	}

	console.log(`\nAPI: ${operations.length} endpoints in src/api/generated/`);
	for(const domain of apiDomains) {
		const note = WRAPPED_API_DOMAINS.has(domain) ? ' (wrapped by hand)' : '';
		console.log(`  ${`${domain}.ts`.padEnd(22)} ${operationsByDomain.get(domain)!.length} functions${note}`);
	}
}

main().catch((error: unknown) => {
	console.error(`\nGeneration failed: ${(error as Error).message}`);
	process.exit(1);
});